// Measures Fraunces 500 advance widths for printable ASCII in a real browser and
// writes js/fontMetrics.js. The layout uses this table instead of the browser's
// font measurement so every device computes the exact same tree.
import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent(`<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Fraunces:wght@500;600&display=swap"><span style="font:500 100px Fraunces">x</span>`);
const EXTRA = '’‘“”…—–·éèêáàâíóöüñçÉ';
const widths = await page.evaluate(async (EXTRA) => {
  await document.fonts.load('500 1000px Fraunces');
  await document.fonts.ready;
  const ctx = document.createElement('canvas').getContext('2d');
  ctx.font = '500 1000px Fraunces';
  const out = [];
  for (let c = 32; c < 127; c++) out.push(Math.round(ctx.measureText(String.fromCharCode(c)).width));
  const extra = {};
  for (const ch of EXTRA) extra[ch] = Math.round(ctx.measureText(ch).width);
  return { out, extra, ok: document.fonts.check('500 1000px Fraunces') };
}, EXTRA);
await browser.close();
if (!widths.ok) throw new Error('Fraunces did not load');
const src = `// Generated by scripts/measure-font.js: Fraunces 500 advance widths in 1/1000 em
// for ASCII 32..126. Do not edit by hand.
const ASCII = [${widths.out.join(',')}];
const EXTRA = ${JSON.stringify(widths.extra)};
const FALLBACK = 560; // accented letters and other scripts
const WIDE = 1000; // emoji and other wide symbols

export function charWidthEm(ch) {
  const c = ch.codePointAt(0);
  if (c >= 32 && c < 127) return ASCII[c - 32] / 1000;
  if (ch in EXTRA) return EXTRA[ch] / 1000;
  if (c > 0xffff || (c >= 0x2600 && c <= 0x27bf)) return WIDE / 1000;
  return FALLBACK / 1000;
}

/** Width of a string in em at Fraunces 500, ignoring kerning. */
export function textWidthEm(text) {
  let w = 0;
  for (const ch of text) w += charWidthEm(ch);
  return w;
}
`;
await writeFile(new URL('../js/fontMetrics.js', import.meta.url), src);
console.log('wrote js/fontMetrics.js', widths.out.slice(33, 40));
